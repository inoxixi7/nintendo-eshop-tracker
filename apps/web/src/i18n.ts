export type Genre = keyof typeof GENRES;

const STORAGE_KEY = 'eshop-tracker:locale';

function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'zh' || saved === 'ja' || saved === 'en') return saved;
  } catch { /* storage unavailable: fall back to the browser language */ }
  const browser = (globalThis.navigator?.language ?? 'zh').toLowerCase();
  return browser.startsWith('ja') ? 'ja' : browser.startsWith('en') ? 'en' : 'zh';
}

export const locale = ref<Locale>(initialLocale());

watch(locale, (value) => {
  try { localStorage.setItem(STORAGE_KEY, value); } catch { /* keep the choice for this visit only */ }
  document.documentElement.lang = value === 'zh' ? 'zh-CN' : value;
}, { immediate: true });

/** Reads locale.value, so templates that call it re-render when the language changes. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return MESSAGES[locale.value][key].replace(/\{(\w+)\}/g, (match, name: string) => String(vars[name] ?? match));
}

export function genreLabel(genre: string): string {
  const names = GENRES[genre as Genre];
  return names === undefined || locale.value === 'ja' ? genre : names[locale.value];
}

export const intlLocale = () => ({ zh: 'zh-CN', ja: 'ja-JP', en: 'en-US' })[locale.value];
